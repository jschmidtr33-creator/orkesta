_TYPO_RNG_SEED = 2026
NONE_LEVEL_OF: dict[str, str] = {}


def _typo(text: str, rng: random.Random) -> str:
    """Un error de tipeo realista: letra faltante, repetida o cambiada de lugar."""
    if len(text) < 6:
        return text
    i = rng.randrange(1, len(text) - 2)
    kind = rng.randrange(3)
    if kind == 0:
        return text[:i] + text[i + 1 :]
    if kind == 1:
        return text[:i] + text[i] + text[i:]
    return text[:i] + text[i + 1] + text[i] + text[i + 2 :]


def examples() -> list[tuple[str, str, str]]:
    """(cargo, nivel, área) — incluye variantes con errores de tipeo y en mayúsculas."""
    rng = random.Random(_TYPO_RNG_SEED)  # noqa: S311  (variantes deterministas, no criptografía)
    out: list[tuple[str, str, str]] = []
    for area, phrases in AREA_PHRASES.items():
        for phrase in phrases:
            levels = rng.sample(list(LEVEL_PREFIXES), 3)
            for level in levels:
                template = rng.choice(LEVEL_PREFIXES[level])
                out.append((template.format(phrase), level, area))
    for area, terms in AREA_TERMS.items():
        for term in terms:
            out.append((term, NONE_LEVEL_OF.get(term, "especialista"), area))
            for level in rng.sample(list(LEVEL_PREFIXES), 2):
                out.append((rng.choice(LEVEL_PREFIXES[level]).format(term), level, area))
    for term in NONE_TERMS:
        out.append((term, "especialista", NONE))
        out.append(
            (
                f"{term} {rng.choice(['Senior', 'Adjunto', 'Principal', 'Asociado', 'de Planta'])}",
                "especialista",
                NONE,
            )
        )
    out += [(title, level, NONE) for title, level in NO_AREA]
    out += EXTRA
    variants = []
    for title, level, area in out:
        roll = rng.random()
        if roll < 0.25:
            variants.append((_typo(title, rng), level, area))
        elif roll < 0.35:
            variants.append((title.upper(), level, area))
    return out + variants
