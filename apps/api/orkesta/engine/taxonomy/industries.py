def _key_regex(key: str) -> str:
    escaped = re.escape(key)
    if key in _WHOLE_WORDS:
        return escaped + r"s?\b"
    return escaped


_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = tuple(
    (code, re.compile(r"\b(?:" + "|".join(_key_regex(k) for k in keys) + ")"))
    for code, (_, keys) in INDUSTRIES.items()
)


@lru_cache(maxsize=20_000)
def classify(text: str) -> str | None:
    """Industria de un texto libre ("Banca minorista" → ``banca_finanzas``) o ``None``."""
    folded = fold(text)
    if not folded:
        return None
    # Gana la palabra clave que aparece primero en el texto ("BANCA-SEGUROS-FINANZAS" es banca);
    # a igual posición, la categoría más específica (orden de INDUSTRIES).
    best: tuple[int, int, str] | None = None
    for order, (code, pattern) in enumerate(_PATTERNS):
        match = pattern.search(folded)
        if match and (best is None or (match.start(), order) < best[:2]):
            best = (match.start(), order, code)
    return best[2] if best else None


def classify_all(texts: Iterable[str]) -> list[str]:
    """Industrias de varios textos, sin repetir y en orden de aparición."""
    out: list[str] = []
    for text in texts:
        code = classify(text)
        if code and code not in out:
            out.append(code)
    return out


# Rangos de empleados como en Sales Navigator.
SIZE_BANDS: tuple[tuple[str, int, int | None], ...] = (
    ("1-10", 1, 10),
    ("11-50", 11, 50),
    ("51-200", 51, 200),
    ("201-500", 201, 500),
    ("501-1000", 501, 1000),
    ("1001-5000", 1001, 5000),
    ("5001-10000", 5001, 10000),
    ("10001+", 10001, None),
)


def size_band(employees: int | None) -> str | None:
    if employees is None or employees <= 0:
        return None
    for band, low, high in SIZE_BANDS:
        if employees >= low and (high is None or employees <= high):
            return band
    return None
